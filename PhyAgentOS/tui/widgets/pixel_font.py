def render_pixel_text(text: str) -> str:
    """Render text as 5-row pixel-font block characters."""
    rows = [""] * 5
    for ch in text.upper():
        glyph = _FONT.get(ch, ("░░░",) * 5)
        for i in range(5):
            rows[i] += glyph[i] + " "
    return "\n".join(rows)


class PixelTitle(Static):
    """A screen title rendered in pixel font."""

    def __init__(self, text: str) -> None:
        super().__init__(render_pixel_text(text), classes="pixel-title")
